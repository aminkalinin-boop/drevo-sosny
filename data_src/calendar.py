def gantt(title, rows):
    W = 1100; LX = 420; MW = (W - LX - 20) / 12; RH = 26; TOP = 70
    H = TOP + len(rows) * RH + 40
    e = html.escape
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="PT Sans, Arial, sans-serif">',
         f'<rect width="{W}" height="{H}" fill="#fbfbf8"/>', f'<text x="16" y="28" font-size="19" font-weight="700" fill="#1d2a22">{e(title)}</text>']
    seasons = [(0, 2, '#eef3f8'), (2, 5, '#eef6ea'), (5, 8, '#fbf5e4'), (8, 11, '#f8efe6'), (11, 12, '#eef3f8')]
    for a, b, c in seasons:
        o.append(f'<rect x="{LX + a * MW:.1f}" y="{TOP - 24}" width="{(b - a) * MW:.1f}" height="{len(rows) * RH + 24}" fill="{c}"/>')
    for i, m in enumerate(MON):
        o.append(f'<text x="{LX + (i + .5) * MW:.1f}" y="{TOP - 8}" font-size="13" text-anchor="middle" fill="#555" font-weight="700">{m}</text>')
        o.append(f'<line x1="{LX + i * MW:.1f}" y1="{TOP - 24}" x2="{LX + i * MW:.1f}" y2="{TOP + len(rows) * RH}" stroke="#dcdcd4"/>')
    prev = None
    for r, (g, name, spans) in enumerate(rows):
        y = TOP + r * RH
        if g != prev and prev is not None:
            o.append(f'<line x1="10" y1="{y}" x2="{W - 10}" y2="{y}" stroke="#b9bdb3"/>')
        prev = g
        if r % 2: o.append(f'<rect x="10" y="{y}" width="{LX - 14}" height="{RH}" fill="#f2f2ec"/>')
        o.append(f'<text x="16" y="{y + 17}" font-size="12.5" fill="#333">{e(name)}</text>')
        col = GC.get(g, '#555')
        for a, b in spans:
            parts = [(a, b)] if b >= a else [(a, 12), (1, b)]
            for x0, x1 in parts:
                o.append(f'<rect x="{LX + (x0 - 1) * MW + 2:.1f}" y="{y + 5}" width="{(x1 - x0 + 1) * MW - 4:.1f}" height="{RH - 10}" rx="5" fill="{col}" opacity=".85"/>')
    lx = 16; ly = H - 14; seen = []
    for g, _, _ in rows:
        if g in seen: continue
        seen.append(g)
        o.append(f'<rect x="{lx}" y="{ly - 11}" width="22" height="13" rx="3" fill="{GC.get(g, "#555")}" opacity=".85"/><text x="{lx + 28}" y="{ly}" font-size="12.5" fill="#444">{e(g)}</text>')
        lx += 44 + len(g) * 7
    o.append('</svg>')
    return '\n'.join(o)


def group(rows):
    order = []
    for g, _, _ in rows:
        if g not in order: order.append(g)
    return [r for g in order for r in rows if r[0] == g]


